"""Slack Block Kit formatter — converts AgentState output into rich Slack blocks."""

from datetime import datetime
from typing import Any

from ..agents.state import AgentState

# Severity → emoji
SEVERITY_EMOJI = {
    "critical": "🔴",
    "high": "🟠",
    "medium": "🟡",
    "low": "🔵",
}


def build_digest_blocks(state: AgentState) -> list[dict[str, Any]]:
    """Return a Slack Block Kit payload for the team digest."""
    blocks: list[dict] = []
    date_str = datetime.utcnow().strftime("%A, %B %d, %Y")

    # ── Header ──────────────────────────────────────────────────────────────
    blocks.append({
        "type": "header",
        "text": {"type": "plain_text", "text": f"🗓  Team Digest — {date_str}", "emoji": True},
    })
    blocks.append({"type": "divider"})

    signals = state.get("developer_signals", [])
    narratives = state.get("developer_narratives", {})
    blockers = state.get("blockers", [])

    if not signals:
        blocks.append(_section("_No developer activity recorded for this period._"))
        return blocks

    # ── Per-developer sections ───────────────────────────────────────────────
    blocker_by_dev: dict[str, list] = {}
    for b in blockers:
        blocker_by_dev.setdefault(b["developer_id"], []).append(b)

    for dev in signals:
        dev_id = dev["developer_id"]
        narrative = narratives.get(dev_id, "_No summary available._")
        dev_blockers = blocker_by_dev.get(dev_id, [])

        # Status indicator
        if any(b["severity"] == "critical" for b in dev_blockers):
            indicator = "🔴"
        elif any(b["severity"] == "high" for b in dev_blockers):
            indicator = "🟠"
        elif dev_blockers:
            indicator = "🟡"
        else:
            indicator = "✅"

        # Stats line
        stats_parts = []
        if dev["commits_today"]:
            stats_parts.append(f"{len(dev['commits_today'])} commit{'s' if len(dev['commits_today']) != 1 else ''}")
        if dev["prs_opened"]:
            stats_parts.append(f"{len(dev['prs_opened'])} PR opened")
        if dev["prs_reviewed"]:
            stats_parts.append(f"{len(dev['prs_reviewed'])} PR reviewed")
        if dev["ci_failures"]:
            stats_parts.append(f"⚠️ {len(dev['ci_failures'])} CI failure{'s' if len(dev['ci_failures']) != 1 else ''}")
        if dev["silence_hours"] > 3:
            stats_parts.append(f"🔇 {dev['silence_hours']:.0f}h silent")

        stats_str = "  ·  ".join(stats_parts) if stats_parts else "No activity"

        blocks.append({
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": (
                    f"{indicator}  *{dev['developer_name']}*\n"
                    f"{narrative}\n"
                    f"_{stats_str}_"
                ),
            },
        })

        # Inline blocker chips
        if dev_blockers:
            blocker_texts = []
            for b in dev_blockers[:3]:
                emoji = SEVERITY_EMOJI.get(b["severity"], "⚪")
                blocker_texts.append(f"{emoji} {b['description'][:80]}")
            blocks.append({
                "type": "context",
                "elements": [{"type": "mrkdwn", "text": text} for text in blocker_texts],
            })

    blocks.append({"type": "divider"})

    # ── Dependency conflicts ─────────────────────────────────────────────────
    conflicts = state.get("conflicts", [])
    if conflicts:
        blocks.append(_section("*⚠️  Coordination needed*"))
        for c in conflicts[:5]:
            overlap = c.get("files_or_services", [])[:3]
            overlap_str = ", ".join(f"`{f}`" for f in overlap)
            blocks.append({
                "type": "context",
                "elements": [{
                    "type": "mrkdwn",
                    "text": (
                        f"*{c['developer_a']}* × *{c['developer_b']}* — "
                        f"{c['risk']}  {overlap_str}"
                    ),
                }],
            })
        blocks.append({"type": "divider"})

    # ── Sprint health ────────────────────────────────────────────────────────
    sprint_risk = state.get("sprint_risk", "")
    if sprint_risk:
        blocks.append({
            "type": "section",
            "text": {"type": "mrkdwn", "text": f"*Sprint health* — {sprint_risk}"},
        })

    # ── Footer ───────────────────────────────────────────────────────────────
    blocks.append({
        "type": "context",
        "elements": [{
            "type": "mrkdwn",
            "text": "Generated by Async Standup Intelligence Layer",
        }],
    })

    return blocks


def _section(text: str) -> dict:
    return {"type": "section", "text": {"type": "mrkdwn", "text": text}}
